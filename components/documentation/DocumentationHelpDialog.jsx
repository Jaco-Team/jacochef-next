"use client";

import Box from "@mui/material/Box";
import Stack from "@mui/material/Stack";
import Typography from "@mui/material/Typography";

import { JacoButton, JacoModal, uiColors, uiRadii, uiTypography } from "@/design-system/shared/ui";

import { hasDocumentationAccess } from "./moduleOptions";

function HelpSection({ title, children }) {
  return (
    <Box>
      <Typography
        sx={{
          mb: 1,
          ...uiTypography.bodyMedium,
          fontWeight: 600,
          color: uiColors.textStrong,
        }}
      >
        {title}
      </Typography>
      <Stack spacing={1}>{children}</Stack>
    </Box>
  );
}

function HelpParagraph({ children }) {
  return (
    <Typography sx={{ ...uiTypography.body, color: uiColors.text, whiteSpace: "pre-wrap" }}>
      {children}
    </Typography>
  );
}

function HelpList({ items }) {
  return (
    <Box
      component="ul"
      sx={{
        m: 0,
        pl: 2.5,
        ...uiTypography.body,
        color: uiColors.text,
        "& li": { mb: 0.75 },
        "& li::marker": { color: uiColors.primary },
      }}
    >
      {items.map((item) => (
        <li key={item}>{item}</li>
      ))}
    </Box>
  );
}

function HelpCallout({ children }) {
  return (
    <Box
      sx={{
        p: 1.5,
        borderRadius: uiRadii.md,
        border: `1px solid ${uiColors.border}`,
        borderLeft: `3px solid ${uiColors.primary}`,
        backgroundColor: uiColors.primarySoft,
      }}
    >
      <Typography sx={{ ...uiTypography.label, color: uiColors.textStrong }}>{children}</Typography>
    </Box>
  );
}

function LibraryHelp({ access }) {
  const canEdit = hasDocumentationAccess(access, "edit_base_access");
  const canDownloadPdf = hasDocumentationAccess(access, "pdf_upload_access");
  const canCreate =
    hasDocumentationAccess(access, "edit_tab_access") &&
    hasDocumentationAccess(access, "edit_tab_new_access");
  const articleItems = [
    "Вверху — к какому модулю относится статья и в какой группе она лежит.",
    "Под заголовком может быть дата обновления и кто последний раз сохранял.",
    "Ниже — сам текст: абзацы, картинки, таблицы.",
    "Если в статье несколько глав, справа будет «Содержание». Нажмите название главы — страница прокрутится к ней. Список остаётся на месте, когда вы листаете статью. Его можно скрыть и снова открыть.",
  ];

  if (canDownloadPdf) {
    articleItems.push(
      "Кнопка «Скачать PDF» сохраняет эту статью файлом. Файл собирает сервер: в него попадает только то, что вам разрешено читать.",
    );
  }

  const questions = [
    "Не вижу статью, которую писали коллеги — проверьте поиск и что выбрана правильная статья слева. Часть текста может быть скрыта ограничениями доступа.",
  ];

  if (canCreate || canEdit) {
    questions.push(
      "Статья пустая — её ещё не написали или вы открыли не ту. Создать или дописать можно во вкладке «Редактор статей».",
    );
  }

  questions.push("На телефоне пропал список — вы уже внутри статьи. Нажмите «К списку».");

  return (
    <Stack spacing={3}>
      <HelpParagraph>
        {canEdit
          ? "Вкладка «База знаний» нужна, чтобы читать готовые статьи. Здесь ничего не пишут и не правят — только смотрят. Если статью нужно изменить, откройте её и нажмите «Редактировать»: вас перенесёт во вкладку «Редактор статей»."
          : "Вкладка «База знаний» нужна, чтобы читать готовые статьи. Здесь ничего не пишут и не правят — только смотрят."}
      </HelpParagraph>

      <HelpSection title="Как устроен экран">
        <HelpList
          items={[
            "Слева — список статей. Они собраны по разделам меню, внутри раздела — по модулям, а внутри модуля — по группам статей.",
            "Справа — текст выбранной статьи.",
            "На телефоне сначала виден список. Когда откроете статью, появится кнопка «К списку», чтобы вернуться назад.",
          ]}
        />
      </HelpSection>

      <HelpSection title="Как найти нужную статью">
        <HelpList
          items={[
            "В поле поиска сверху слева начните вводить название статьи, название модуля или группы.",
            "Список сразу сузится. Если ничего не нашлось — попробуйте другое слово или очистите поиск.",
            "Нажмите на название статьи в списке — справа откроется её текст.",
          ]}
        />
      </HelpSection>

      <HelpSection title="Что видно в статье">
        <HelpList items={articleItems} />
        <HelpCallout>
          Иногда часть текста скрыта. Это не ошибка. Автор статьи мог закрыть кусок текста для части
          сотрудников. Тогда на месте скрытого фрагмента будет пометка, что доступ ограничен. Если
          вам нужен этот текст — обратитесь к тому, кто ведёт документацию, или к руководителю.
        </HelpCallout>
      </HelpSection>

      {canEdit || canCreate ? (
        <HelpSection title="Как перейти к правке">
          <HelpList
            items={[
              "Откройте статью.",
              ...(canEdit
                ? [
                    "Нажмите «Редактировать» справа сверху.",
                    "Откроется вкладка «Редактор статей» с этой же статьей.",
                  ]
                : []),
            ]}
          />
          {canCreate ? (
            <HelpParagraph>
              Если статей ещё нет, на экране будет кнопка «Создать статью» — она тоже откроет
              редактор.
            </HelpParagraph>
          ) : null}
        </HelpSection>
      ) : null}

      <HelpSection title="Частые вопросы">
        <HelpList items={questions} />
      </HelpSection>
    </Stack>
  );
}

function EditorHelp({ access }) {
  const canCreate = hasDocumentationAccess(access, "edit_tab_new_access");
  const canEdit = hasDocumentationAccess(access, "edit_tab_edit_access");
  const canUseAi = hasDocumentationAccess(access, "edit_tab_ai_auto_access");
  const canUseBlocks = hasDocumentationAccess(access, "edit_tab_block_access");
  const startItems = [
    "Сверху выберите модуль — раздел системы, про который пишете.",
    "Если у модуля уже есть статьи, выберите нужную в поле «Статья модуля».",
  ];

  if (canCreate) {
    startItems.push("Чтобы начать с нуля, нажмите «Новая статья».");
  }

  startItems.push(
    "Заполните «Название статьи» — так её увидят в базе знаний.",
    "В поле «Группа статей» можно выбрать уже существующую группу или вписать новую. Если оставить пустым — статья будет без группы.",
  );

  const writeItems = [
    "Пишите в большом поле редактора, как в обычном текстовом документе.",
    "Чтобы строка стала главой, выберите в списке форматов «Заголовок». Просто жирный текст в содержание не попадёт.",
    "Кнопки сверху: жирный, курсив, списки, ссылки, картинки, таблицы.",
    "Картинку можно вставить кнопкой с изображением. Файл не должен быть больше 5 МБ.",
  ];

  if (canUseAi) {
    writeItems.push(
      "«Сгенерировать текст ИИ» подставит черновик прямо в статью. Проверьте текст глазами и поправьте перед сохранением — ИИ может ошибаться.",
    );
  }

  const viewItems = [];

  if (canEdit) {
    viewItems.push(
      "После сохранения статья открывается в режиме просмотра. Чтобы снова править — «Редактировать».",
    );
  }

  viewItems.push(
    "В режиме просмотра справа может быть «Содержание». Нажмите главу, чтобы перейти к ней. Список не уезжает при прокрутке, его можно скрыть.",
    "«Отмена» сбрасывает несохранённые правки и возвращает последний сохранённый вариант.",
    "Внизу может быть «История изменений». Там видно прошлые версии. «Восстановить» вернёт статью к выбранной версии; текущий текст сохранится в истории.",
  );

  return (
    <Stack spacing={3}>
      <HelpParagraph>
        Вкладка «Редактор статей» нужна, чтобы писать и менять статьи по модулям. Один модуль может
        иметь несколько статей. Статьи можно складывать в группы, например «Начало», «Частые
        вопросы», «Ошибки».
      </HelpParagraph>

      <HelpSection title="С чего начать">
        <HelpList items={startItems} />
        <HelpCallout>
          Пока статья не сохранена, в базе знаний её нет. После сохранения она появится во вкладке
          «База знаний».
        </HelpCallout>
      </HelpSection>

      <HelpSection title="Как писать текст">
        <HelpList items={writeItems} />
      </HelpSection>

      {canUseAi ? (
        <HelpSection title="Помощь от ИИ">
          <HelpParagraph>
            Это чат с вопросами про выбранный модуль. Он не меняет статью. Черновик в текст статьи
            подставляет только кнопка «Сгенерировать текст ИИ».
          </HelpParagraph>
          <HelpList
            items={[
              canEdit
                ? "Кнопка видна, когда статья открыта для правки, рядом с «Сгенерировать текст ИИ». Если статья только читается, сначала нажмите «Редактировать»."
                : "Кнопка видна, когда статья открыта для правки, рядом с «Сгенерировать текст ИИ».",
              "Нажмите «Помощь от ИИ». Откроется окно, в заголовке будет название модуля.",
              "Внизу напишите вопрос и нажмите «Отправить». Клавиша Enter тоже отправляет. Shift+Enter переносит строку, не отправляя.",
              "Ваши сообщения стоят справа, ответы — слева. Пока ответ готовится, подождите и не отправляйте тот же вопрос ещё раз.",
              "Если отправить не получилось, вопрос останется в поле. Можно поправить его и нажать «Отправить» снова.",
              "Если старые сообщения не открылись, в окне будет кнопка «Повторить».",
            ]}
          />
          <HelpCallout>
            Переписка хранится только у вас и только для этого модуля. Коллеги её не видят. У
            другого модуля свой отдельный чат. Закрыли окно или вышли из правки — сообщения не
            стираются: откройте помощь по тому же модулю, и они снова будут на месте.
          </HelpCallout>
          <HelpParagraph>
            Ответ сам в статью не попадает. Если он пригодился, перенесите нужное в текст и
            сохраните статью. ИИ может ошибаться, поэтому сверьтесь с уже написанными статьями
            модуля.
          </HelpParagraph>
        </HelpSection>
      ) : null}

      {canUseBlocks ? (
        <>
          <HelpSection title="Блоки доступа — зачем они">
            <HelpParagraph>
              Иногда нужно, чтобы часть статьи видели не все, а только нужные люди. Например,
              служебную инструкцию — только управляющие, а общий текст — все.
            </HelpParagraph>
            <HelpList
              items={[
                "Выделите мышкой тот кусок текста, который хотите закрыть.",
                "Нажмите «Блок доступа» на панели редактора.",
                "Кусок окрасится в розовый — это и есть ограниченный фрагмент.",
                "Справа появится карточка этого блока. Там можно указать, кому он виден.",
              ]}
            />
          </HelpSection>

          <HelpSection title="Как настроить, кому виден блок">
            <HelpList
              items={[
                "«Кому» — конкретные сотрудники. Начните вводить фамилию или имя и выберите из списка.",
                "«Должности» — все сотрудники с выбранной должностью.",
                "«Необходимые права» — если поле активно, можно выбрать коды прав модуля. Если написано, что система прав не подключена, это поле пока недоступно: права для этого модуля на сервере не настроены.",
                "«Условие просмотра»: «Хотя бы одно условие» — достаточно совпасть по одному из заполненных списков. «Все условия» — должны совпасть все заполненные списки сразу.",
              ]}
            />
            <HelpCallout>
              Если в карточке блока ничего не выбрать, розовый фрагмент увидят все, у кого открыт
              этот модуль. Розовая рамка сама по себе доступ не закрывает — закрывают выбранные
              сотрудники, должности или права.
            </HelpCallout>
          </HelpSection>

          <HelpSection title="Как убрать ограничение">
            <HelpList
              items={[
                "Поставьте курсор внутрь розового блока.",
                "Нажмите «Снять ограничение» рядом с «Блок доступа». Текст останется, рамка исчезнет.",
                "Можно выделить только часть текста внутри розового блока и нажать «Снять ограничение» — ограничение снимется только с этой части.",
                "То же самое можно сделать кнопкой «Убрать ограничение» в карточке справа.",
              ]}
            />
            <HelpParagraph>
              На блоке сверху написана подсказка «Ограниченный доступ». Если кликнуть по блоку, над
              ним может появиться короткая панель с той же кнопкой «Снять ограничение».
            </HelpParagraph>
          </HelpSection>
        </>
      ) : null}

      <HelpSection title="Как сохранить">
        <HelpList
          items={
            canUseBlocks
              ? [
                  "Нажмите «Сохранить».",
                  "Откроется окно: в нём перечислены выбранные ограничения или написано, что ограничений нет.",
                  "Проверьте список и снова нажмите «Сохранить».",
                  "Если сохранить не удалось и появилось сообщение об ошибке — возможно, у вас нет права править статьи. Тогда обратитесь к тому, кто выдаёт доступы.",
                ]
              : [
                  "Нажмите «Сохранить».",
                  "Если сохранить не удалось и появилось сообщение об ошибке — возможно, у вас нет права править статьи. Тогда обратитесь к тому, кто выдаёт доступы.",
                ]
          }
        />
      </HelpSection>

      <HelpSection title="Просмотр, отмена и история">
        <HelpList items={viewItems} />
      </HelpSection>

      {canUseBlocks ? (
        <HelpSection title="Частые вопросы">
          <HelpList
            items={[
              "Не могу нажать «Снять ограничение» — кнопка включается только когда курсор стоит внутри розового блока.",
              "Блоки пересекаются — нельзя накладывать один блок доступа на другой. Сначала снимите старое ограничение.",
              "После сохранения права в блоке «съехали» — откройте статью снова и проверьте карточки справа. Идентификаторы блоков подставляются из ответа сервера.",
              "Поле прав серое — для выбранного модуля права не подключены. Можно ограничивать по сотрудникам и должностям.",
            ]}
          />
        </HelpSection>
      ) : null}
    </Stack>
  );
}

export default function DocumentationHelpDialog({ open, tab, access = {}, onClose }) {
  const isEditor = tab === "editor";

  return (
    <JacoModal
      open={open}
      onClose={onClose}
      title={isEditor ? "Как пользоваться редактором статей" : "Как пользоваться базой знаний"}
      maxWidth="md"
      containedDesktopScroll
      desktopMaxHeight="85dvh"
      actions={
        <JacoButton
          compact
          onClick={onClose}
        >
          Понятно
        </JacoButton>
      }
    >
      {isEditor ? <EditorHelp access={access} /> : <LibraryHelp access={access} />}
    </JacoModal>
  );
}
